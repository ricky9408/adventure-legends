#!/usr/bin/env python3
"""Original code-native lane beetle and court post; existing RGB555 palette and 16px anchor."""
from pathlib import Path
from PIL import Image, ImageDraw
from generate_assets import P, PAL
ROOT=Path(__file__).resolve().parents[1]

def turn(im):
 # Public direction numbering is 0 down, 1 up, 2 left, 3 right. Rotate one
 # whole procedural frame rather than independently drifting silhouettes.
 return [im,im.transpose(Image.Transpose.ROTATE_180),
         im.transpose(Image.Transpose.ROTATE_270),im.transpose(Image.Transpose.ROTATE_90)]

def beetle(warning):
 im=Image.new('P',(16,16),0);im.putpalette(PAL);d=ImageDraw.Draw(im)
 def poly(points,c):d.polygon(points,fill=P[c])
 def box(rect,c):d.rectangle(rect,fill=P[c])
 poly([(4,5),(6,3),(9,3),(11,5),(12,9),(10,12),(5,12),(3,9)],'ink')
 poly([(5,5),(7,4),(9,4),(11,6),(11,9),(9,11),(6,11),(4,9)],'stone2')
 box((6,5,9,6),'silver');box((7,7,8,10),'slate')
 box((2,7,3,8),'silver');box((12,7,13,8),'silver')
 box((3,10,4,11),'stone4');box((11,10,12,11),'stone4')
 box((5,7,6,8),'white');box((9,7,10,8),'white')
 box((6,8,6,8),'ink');box((9,8,9,8),'ink')
 horn='gold3' if warning else 'fire1'
 box((5,12,6,13),horn);box((9,12,10,13),horn)
 if warning:box((4,5,4,9),'gold3');box((11,5,11,9),'gold3')
 return im

def post(warning):
 """Planted court piling. The tell raises gold braces; the shove uses the planted frame."""
 im=Image.new('P',(16,16),0);im.putpalette(PAL);d=ImageDraw.Draw(im)
 def box(rect,c):d.rectangle(rect,fill=P[c])
 box((6,3,9,12),'water1');box((7,4,8,11),'water3')
 box((4,13,11,14),'stone2');box((5,13,6,13),'stone4');box((9,13,10,13),'stone4')
 box((6,6,6,6),'white');box((9,6,9,6),'white')
 box((6,7,6,7),'ink');box((9,7,9,7),'ink')
 if warning:
  box((2,4,4,8),'gold3');box((11,4,13,8),'gold3')
  box((5,4,5,8),'gold2');box((10,4,10,8),'gold2')
  box((6,1,9,2),'gold3')
 else:
  box((4,8,5,10),'teal1');box((10,8,11,10),'teal2')
 return im

def dump(name,frames):
 rows=['static const unsigned char %s[8][256]={'%name]
 for im in frames:rows.append('{'+','.join(map(str,im.tobytes()))+'},')
 rows.append('};')
 return rows

beetle_frames=[frame for warning in (False,True) for frame in turn(beetle(warning))]
post_frames=[frame for warning in (False,True) for frame in turn(post(warning))]
rows=['/* Generated by assets/generate_enemy_tactics.py; original procedural art. */']
rows+=dump('charger_pixels',beetle_frames)
rows+=dump('sentry_pixels',post_frames)
(ROOT/'src/enemy_tactics_art.inc').write_text('\n'.join(rows)+'\n')
sheet=Image.new('P',(16*4,16*4),0);sheet.putpalette(PAL)
for i,im in enumerate(beetle_frames+post_frames):sheet.paste(im,(i%4*16,i//4*16))
sheet.resize((256,256),Image.Resampling.NEAREST).save(ROOT/'assets/enemy_tactics_preview.png')
