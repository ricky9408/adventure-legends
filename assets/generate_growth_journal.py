for i in range(10):LABELS[f'DIGIT_{i}']=str(i)
def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--font',default=os.environ.get('GBA_NOTO_FONT',gbj_font.FALLBACK));p.add_argument('--latin-font',default=os.environ.get('GBA_LATIN_FONT','/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf'));a=p.parse_args()
 gbj_font.FALLBACK=a.font;gbj_font.latin_fallback=lambda:ImageFont.truetype(a.latin_font,8)
 items=[];lines=[]
 for name,value in LABELS.items():
  im=gbj_font.render_text(value,15);w=im.width;assert w<=214,(name,value,w);variants=[]
  for align in (0,1):
   runs=[]
   for y in range(15):
    masks=[sum(1<<b for b in (0,1) if 0<=x+b-align<w and im.getpixel((x+b-align,y))) for x in range(0,w+align,2)];x=0
    while x<len(masks):
     mask=masks[x]
     if not mask:x+=1;continue
     end=x+1
     while end<len(masks) and masks[end]==mask and end-x<255:end+=1
     runs.append((y*120+x,end-x,mask));x=end
   decoded=Image.new('1',(w+align,15))
   for offset,count,mask in runs:
    for half in range(count):
     yy,xx=divmod(offset+half,120)
     for bit in (0,1):
      if mask&(1<<bit):decoded.putpixel((xx*2+bit,yy),1)
   assert decoded.crop((align,0,w+align,15)).tobytes()==im.tobytes(),(name,align)
   variants.append(runs);lines.append(f'static const UiRun gj_{name}_{align}[] = {{'+(','.join('{%d,%d,%d}'%r for r in runs) if runs else '{0,0,0}')+'};\n')
  items.append((name,w,variants))
 lines=gbj_font.deduplicate_spans(''.join(lines)).splitlines(True)
 h='#ifndef EMBER_GROWTH_JOURNAL_TEXT_H\n#define EMBER_GROWTH_JOURNAL_TEXT_H\n#include "ui.h"\nenum {\n'+''.join(f' GJ_{n},\n'for n,_,_ in items)+' GJ_COUNT };\nextern const UiText growth_journal_texts[GJ_COUNT];\n#endif\n'
 (ROOT/'src/growth_journal_text.h').write_text(h)
 lines.append('const UiText growth_journal_texts[GJ_COUNT] = {\n')
 for n,w,v in items:lines.append('{%d,15,0,{gj_%s_0,gj_%s_1},{%d,%d}},\n'%(w,n,n,len(v[0]),len(v[1])))
 lines.append('};\n');parts=[];part=''
 for line in lines:
  if len((part+line).encode())>32000:parts.append(part);part=''
  part+=line
 if part:parts.append(part)
 d=ROOT/'src/growth_journal_text_data';d.mkdir(exist_ok=True)
 for f in d.glob('part_*.inc'):f.unlink()
 for i,value in enumerate(parts):(d/f'part_{i:03}.inc').write_text(value)
 (ROOT/'src/growth_journal_text.c').write_text('/* Generated by assets/generate_growth_journal.py. */\n#include "growth_journal_text.h"\n'+''.join(f'#include "growth_journal_text_data/part_{i:03}.inc"\n'for i in range(len(parts))))
 (ROOT/'assets/growth_journal_metrics.json').write_text(json.dumps({n:{'width':w,'height':15,'text':LABELS[n]}for n,w,_ in items},ensure_ascii=False,indent=2)+'\n')
 print(f'{len(items)} journal labels; {len(parts)} bounded source chunks')
if __name__=='__main__':main()
